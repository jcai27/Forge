import {test,expect} from '@playwright/test';
test('create a project, build and improve an agent, deploy and approve a real fixture operation',async({page})=>{
 await page.goto('/dashboard');
 await page.getByRole('button',{name:'Open local demo workspace'}).click();
 await expect(page.getByRole('heading',{name:'Your agent factory'})).toBeVisible();
 await page.getByRole('link',{name:'Create agent',exact:true}).first().click();
 await page.getByLabel('Project name',{exact:true}).fill('Browser acceptance project');
 await page.getByRole('button',{name:'Create project',exact:true}).click();
 await expect(page.getByLabel('Project',{exact:true})).toContainText('Browser acceptance project');
 await page.getByRole('button',{name:'Restaurant order entry'}).click();
 await page.getByRole('checkbox',{name:/Fictional Business ERP/}).check();
 await page.getByRole('button',{name:'Create and start build'}).click();
 await expect(page).toHaveURL(/\/agents\/[^/]+\/build/);
 const agentId=page.url().split('/agents/')[1].split('/')[0];
 await expect(page.getByText('ready for review',{exact:true}).first()).toBeVisible({timeout:60000});
 await expect(page.getByText('Iteration 3',{exact:true})).toBeVisible();
 await expect(page.getByText(/Customer alias red toms/).first()).toBeVisible();
 await page.getByRole('link',{name:'Evaluations',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Evaluation lab',exact:true})).toBeVisible();
 await expect(page.getByRole('heading',{name:/Scenario library/})).toContainText('36');
 await page.getByRole('link',{name:'Versions',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Compare immutable configurations'})).toBeVisible();
 await expect(page.getByRole('heading',{name:'rules',exact:true})).toBeVisible();
 await page.getByRole('link',{name:'Deployments',exact:true}).click();
 await page.getByRole('button',{name:'Approve candidate'}).click();
 await expect(page.getByRole('button',{name:'Deploy approved version'})).toBeEnabled();
 await page.getByRole('button',{name:'Deploy approved version'}).click();
 await expect(page.getByRole('button',{name:'Invoke agent'})).toBeEnabled();
 await page.getByLabel('Business request').fill('Harbor Bistro: 2 kg red toms');
 await page.getByRole('button',{name:'Invoke agent'}).click();
 await expect(page).toHaveURL(/\/runs\//);
 const runURL=page.url();
 await expect(page.getByText('waiting for approval',{exact:true})).toBeVisible();
 await page.getByRole('link',{name:'Approvals',exact:true}).click();
 await page.getByRole('button',{name:'Approve operation'}).first().click();
 await page.goto(runURL);
 await expect(page.getByText('completed',{exact:true})).toBeVisible();
 await expect(page.getByText('approval applied',{exact:true})).toBeVisible();
 await page.reload();
 await expect(page.getByText('completed',{exact:true})).toBeVisible();
 await page.goto(`/agents/${agentId}/studio`);
 await expect(page.getByRole('heading',{name:'Workflow',exact:true})).toBeVisible();
 await page.goto('/dashboard');
 await page.screenshot({path:'test-results/dashboard.png',fullPage:true});
});
