import {test,expect} from '@playwright/test';

test('invite a teammate, switch workspaces, change access and revoke an existing session',async({page,browser})=>{
  const rateLimited:string[]=[];
  page.on('response',response=>{if(response.status()===429)rateLimited.push(response.url());});
  await page.goto('/dashboard');
  await page.getByRole('button',{name:'Open local demo workspace'}).click();
  await expect(page.getByRole('heading',{name:'Your agent factory'})).toBeVisible();
  await page.getByRole('link',{name:'Settings',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Workspace members'})).toBeVisible();
  await expect(page.getByLabel('Role for demo@agentfactory.local')).toBeDisabled();
  await expect(page.getByRole('button',{name:'Remove demo@agentfactory.local'})).toBeDisabled();
  const email='browser-teammate@example.invalid',password='local-browser-teammate-password',base='http://127.0.0.1:8100';
  await page.getByLabel('Teammate email').fill(email);
  await page.getByLabel('Invitation role').selectOption('editor');
  await page.getByRole('button',{name:'Create invitation',exact:true}).click();
  const code=await page.getByLabel('New invitation code').inputValue();
  expect(code.length).toBeGreaterThanOrEqual(32);
  await page.getByRole('button',{name:'Dismiss invitation code'}).click();
  await expect(page.getByLabel('New invitation code')).toHaveCount(0);
  const context=await browser.newContext();
  const recipient=await context.newPage();
  recipient.on('response',response=>{if(response.status()===429)rateLimited.push(response.url());});
  try {
    await recipient.goto('http://127.0.0.1:3100/dashboard');
    await recipient.getByRole('button',{name:'Create an account',exact:true}).click();
    await recipient.getByLabel('Email',{exact:true}).fill(email);
    await recipient.getByLabel('Password',{exact:true}).fill(password);
    await recipient.getByLabel('Organization name').fill('Teammate personal workspace');
    await recipient.getByRole('button',{name:'Create workspace',exact:true}).click();
    await expect(recipient.getByRole('heading',{name:'Your agent factory'})).toBeVisible();
    await recipient.getByRole('link',{name:'Settings',exact:true}).click();
    await recipient.getByLabel('Invitation code',{exact:true}).fill(code);
    await recipient.getByRole('button',{name:'Accept invitation and open workspace'}).click();
    await expect(recipient.getByRole('heading',{name:'Your agent factory'})).toBeVisible();
    await recipient.getByRole('link',{name:'Settings',exact:true}).click();
    await expect(recipient.getByRole('table',{name:'Workspace members'})).toContainText('demo@agentfactory.local');
    await expect(recipient.getByRole('heading',{name:'Invite a teammate'})).toHaveCount(0);
    const profile=await recipient.request.get(`${base}/auth/me`,{headers:{Authorization:'Bearer '+await recipient.evaluate(()=>localStorage.getItem('factory-token'))}});
    const me=await profile.json();
    expect(me.role).toBe('editor');
    const original=me.memberships.find((item:{organization_name:string})=>item.organization_name==='Teammate personal workspace');
    const target=me.organization.id;
    await recipient.getByLabel('Workspace',{exact:true}).selectOption(original.org_id);
    await recipient.getByRole('button',{name:'Switch workspace',exact:true}).click();
    await expect(recipient.getByRole('heading',{name:'Your agent factory'})).toBeVisible();
    await recipient.getByRole('link',{name:'Settings',exact:true}).click();
    await expect(recipient.getByRole('table',{name:'Workspace members'})).not.toContainText('demo@agentfactory.local');
    await recipient.getByLabel('Workspace',{exact:true}).selectOption(target);
    await recipient.getByRole('button',{name:'Switch workspace',exact:true}).click();
    await expect(recipient.getByRole('heading',{name:'Your agent factory'})).toBeVisible();
    await page.reload();
    await expect(page.getByLabel(`Role for ${email}`)).toHaveValue('editor');
    const changed=page.waitForResponse(response=>response.request().method()==='PATCH'&&response.url().includes('/organizations/members/'));
    await page.getByLabel(`Role for ${email}`).selectOption('viewer');
    expect((await changed).status()).toBe(200);
    const recipientToken=await recipient.evaluate(()=>localStorage.getItem('factory-token'));
    const forbidden=await recipient.request.post(`${base}/projects`,{headers:{Authorization:`Bearer ${recipientToken}`},data:{name:'Viewer cannot create'}});
    expect(forbidden.status()).toBe(403);
    const removed=page.waitForResponse(response=>response.request().method()==='DELETE'&&response.url().includes('/organizations/members/'));
    await page.getByRole('button',{name:`Remove ${email}`,exact:true}).click();
    expect((await removed).status()).toBe(204);
    await expect(page.getByRole('table',{name:'Workspace members'})).not.toContainText(email);
    expect((await recipient.request.get(`${base}/auth/me`,{headers:{Authorization:`Bearer ${recipientToken}`}})).status()).toBe(401);
    await recipient.reload();
    await recipient.getByRole('button',{name:'Sign in again',exact:true}).click();
    await recipient.getByLabel('Email',{exact:true}).fill(email);
    await recipient.getByLabel('Password',{exact:true}).fill(password);
    await recipient.getByRole('button',{name:'Sign in',exact:true}).click();
    await expect(recipient.getByRole('heading',{name:'Your agent factory'})).toBeVisible();
    await recipient.getByRole('link',{name:'Settings',exact:true}).click();
    await expect(recipient.getByRole('table',{name:'Workspace members'})).not.toContainText('demo@agentfactory.local');
    await expect(recipient.getByRole('heading',{name:'Your workspaces'})).toHaveCount(0);
  } finally {await context.close();}
  expect(rateLimited).toEqual([]);
});
