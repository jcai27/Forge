import {test,expect} from '@playwright/test';

test('redirect a paused build through a new immutable configuration and fresh evaluation',async({page})=>{
  await page.goto('/dashboard');
  await page.getByRole('button',{name:'Open local demo workspace'}).click();
  await expect(page.getByRole('heading',{name:'Your agent factory'})).toBeVisible();
  const token=await page.evaluate(()=>localStorage.getItem('factory-token'));
  const headers={Authorization:`Bearer ${token}`}, base='http://127.0.0.1:8100';
  const projects=await (await page.request.get(`${base}/projects`,{headers})).json();
  const connections=await (await page.request.get(`${base}/integrations`,{headers})).json();
  const fixture=connections.items.find((item:{kind:string})=>item.kind==='fixture');
  const created=await page.request.post(`${base}/agents`,{headers,data:{project_id:projects.items[0].id,request:'Process restaurant orders with approved catalog tools',template:'orders',connection_ids:[fixture.id]}});
  expect(created.status()).toBe(201);
  const agent=await created.json();
  const started=await page.request.post(`${base}/agents/${agent.id}/builds`,{headers,data:{}});
  expect(started.status()).toBe(201);
  const build=await started.json();
  const paused=await page.request.post(`${base}/builds/${build.id}/pause`,{headers,data:{}});
  expect(paused.status()).toBe(200);
  await page.goto(`/agents/${agent.id}/build`);
  await expect(page.getByText('paused',{exact:true}).first()).toBeVisible();
  await page.getByText('Redirect this build',{exact:true}).click();
  const spec=agent.version.spec;
  spec.rules.resolve_aliases=true;
  spec.rules.fuzzy_match=true;
  spec.purpose='Resolve restaurant customer aliases and conservative catalog matches before preparing orders';
  spec.requirements.objective=spec.purpose;
  await page.getByLabel('Redirection reason').fill('The clarified workflow must resolve catalog aliases before preparing orders.');
  await page.getByLabel('Revised build configuration').fill(JSON.stringify(spec,null,2));
  const response=page.waitForResponse(result=>result.url()===`${base}/builds/${build.id}/redirect`);
  await page.getByRole('button',{name:'Save revision and redirect build'}).click();
  expect((await response).status()).toBe(201);
  await expect(page.getByRole('status',{name:'Build status'})).toHaveText('ready for review',{timeout:60000});
  const result=await (await page.request.get(`${base}/builds/${build.id}`,{headers})).json();
  expect(result.checkpoint.version_id).not.toBe(agent.version.id);
  expect(result.checkpoint.redirections).toHaveLength(1);
  expect(result.checkpoint.validation_scorecard.score).toBe(1);
  const versions=await (await page.request.get(`${base}/agents/${agent.id}/versions`,{headers})).json();
  expect(versions.items.find((version:{id:string})=>version.id===agent.version.id).spec.rules.resolve_aliases).toBe(false);
});
