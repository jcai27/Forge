import {test,expect} from '@playwright/test';

test('correct a local SDK test proposal before importing and executing evaluation evidence',async({page})=>{
  const rateLimited:string[]=[];
  page.on('response',response=>{if(response.status()===429)rateLimited.push(response.url());});
  await page.goto('/dashboard');
  await page.getByRole('button',{name:'Open local demo workspace'}).click();
  await expect(page.getByRole('heading',{name:'Overview'})).toBeVisible();
  const token=await page.evaluate(()=>localStorage.getItem('factory-token'));
  const headers={Authorization:`Bearer ${token}`},base='http://127.0.0.1:8100';
  const agents=await (await page.request.get(`${base}/agents`,{headers})).json();
  const agent=agents.items.find((item:{name:string})=>item.name==='Local SDK proposal review fixture');
  expect(agent).toBeDefined();
  const detail=await (await page.request.get(`${base}/agents/${agent.id}`,{headers})).json();
  const job=detail.builds.find((item:{state:string})=>item.state==='WAITING_FOR_APPROVAL');
  expect(job).toBeDefined();
  const checkpoint=await (await page.request.get(`${base}/builds/${job.id}`,{headers})).json();
  expect(checkpoint.iterations).toHaveLength(0);
  expect(checkpoint.checkpoint.test_proposals.cases).toHaveLength(6);
  const suites=await (await page.request.get(`${base}/agents/${agent.id}/suites`,{headers})).json();
  const suiteId=suites.items[0].id;
  const originalCases=await (await page.request.get(`${base}/suites/${suiteId}/cases`,{headers})).json();
  expect(originalCases.items).toHaveLength(0);
  await page.goto(`/agents/${agent.id}/build`);
  await expect(page.getByRole('heading',{name:'Review proposed evaluation cases'})).toBeVisible();
  await expect(page.getByRole('table',{name:'Proposed scenario summary'}).getByRole('row')).toHaveCount(7);
  await expect(page.getByText(/do not count as evidence until execution and grading/)).toBeVisible();
  const editor=page.getByLabel('Proposed test plan');
  const proposed=JSON.parse(await editor.inputValue());
  expect(proposed.cases[0].assertions[0].value).toBe(901);
  await editor.fill('{invalid JSON');
  await page.getByRole('button',{name:'Accept corrected cases and resume'}).click();
  await expect(page.getByText('Enter a valid proposed test plan.')).toBeVisible();
  await expect(editor).toHaveAttribute('aria-invalid','true');
  const unchanged=await (await page.request.get(`${base}/builds/${job.id}`,{headers})).json();
  expect(unchanged.state).toBe('WAITING_FOR_APPROVAL');
  expect(unchanged.checkpoint.accepted_case_ids).toBeUndefined();
  const unsafe=structuredClone(proposed);
  unsafe.cases[0].source='live_read_only';
  unsafe.cases[0].environment={live_connection_ids:['unapproved']};
  await editor.fill(JSON.stringify(unsafe,null,2));
  const denied=page.waitForResponse(response=>response.url()===`${base}/builds/${job.id}/test-proposals/accept`);
  await page.getByRole('button',{name:'Accept corrected cases and resume'}).click();
  expect((await denied).status()).toBe(403);
  expect(JSON.parse(await editor.inputValue()).cases[0].source).toBe('live_read_only');
  const stillEmpty=await (await page.request.get(`${base}/suites/${suiteId}/cases`,{headers})).json();
  expect(stillEmpty.items).toHaveLength(0);
  proposed.cases[0].assertions[0].value=900;
  proposed.rationale='Reviewed the fictional catalog prices independently and corrected Tomatoes to 900 cents.';
  await editor.fill(JSON.stringify(proposed,null,2));
  await expect(editor).toHaveAttribute('aria-invalid','false');
  const accepted=page.waitForResponse(response=>response.url()===`${base}/builds/${job.id}/test-proposals/accept`);
  await page.getByRole('button',{name:'Accept corrected cases and resume'}).click();
  expect((await accepted).status()).toBe(200);
  await expect(page.getByRole('heading',{name:'Review proposed evaluation cases'})).toHaveCount(0);
  await expect(page.getByRole('status',{name:'Build status'})).toHaveText('ready for review',{timeout:60000});
  const completed=await (await page.request.get(`${base}/builds/${job.id}`,{headers})).json();
  expect(completed.checkpoint.test_proposals).toBeNull();
  expect(completed.checkpoint.accepted_case_ids).toHaveLength(6);
  expect(completed.checkpoint.test_design_reviewed_by).toBeTruthy();
  expect(completed.checkpoint.validation_scorecard.passed).toBe(2);
  expect(completed.checkpoint.validation_scorecard.score).toBe(1);
  const cases=await (await page.request.get(`${base}/suites/${suiteId}/cases`,{headers})).json();
  expect(cases.items).toHaveLength(6);
  expect(cases.items.find((item:{name:string})=>item.name==='Proposed Tomatoes').assertions[0].value).toBe(900);
  const duplicate=await page.request.post(`${base}/builds/${job.id}/test-proposals/accept`,{headers,data:proposed});
  expect(duplicate.status()).toBe(409);
  await page.reload();
  await expect(page.getByRole('status',{name:'Build status'})).toHaveText('ready for review');
  await expect(page.getByRole('heading',{name:'Review proposed evaluation cases'})).toHaveCount(0);
  await page.getByRole('link',{name:'Evaluations',exact:true}).click();
  await expect(page.getByRole('heading',{name:/Scenario library/})).toContainText('6');
  await expect(page.getByText('Proposed Tomatoes',{exact:true})).toBeVisible();
  expect(rateLimited,'Browser interactions must stay within the API request limit').toEqual([]);
});
